def _split_message(text: str, max_len: int = 400) -> list[str]:
    """Split a long LLM response into natural Telegram-sized chunks."""
    text = text.strip()
    if len(text) <= max_len:
        return [text]
    paragraphs = [p.strip() for p in text.split("\n\n") if p.strip()]
    if not paragraphs:
        return [text]
    parts: list[str] = []
    for para in paragraphs:
        if len(para) <= max_len:
            parts.append(para)
        else:
            sentences = re.split(r"(?<=[.!?])\s+", para)
            current = ""
            for sent in sentences:
                if current and len(current) + len(sent) + 1 > max_len:
                    parts.append(current.strip())
                    current = sent
                else:
                    current = f"{current} {sent}".strip() if current else sent
            if current:
                parts.append(current.strip())
    merged: list[str] = []
    for p in parts:
        if merged and len(merged[-1]) < 30 and len(merged[-1]) + len(p) + 1 <= max_len:
            merged[-1] = f"{merged[-1]} {p}"
        else:
            merged.append(p)
    return merged or [text]


class LLMAgent:
    def __init__(self, api_key: str, base_url: str, default_model: str = "llama-3.3-70b-versatile") -> None:
        self.api_key = api_key
        self.base_url = base_url.rstrip("/")
        self.default_model = default_model
        self._http: httpx.AsyncClient | None = None

    async def _client(self) -> httpx.AsyncClient:
        if self._http is None or self._http.is_closed:
            self._http = httpx.AsyncClient(timeout=30)
        return self._http

    @property
    def ready(self) -> bool:
        return bool(self.api_key)

    def _build_system(self, profile: AgentProfileOut, examples: list[AgentExampleOut],
                      language_mode: str = "auto") -> str:
        if language_mode == "ru":
            lang_instruction = (
                "IMPORTANT: Always reply in Russian regardless of the user's language. "
                "Keep replies concise and natural — write like a real person in a Telegram chat."
            )
        elif language_mode == "en":
            lang_instruction = (
                "IMPORTANT: Always reply in English regardless of the user's language. "
                "Keep replies concise and natural — write like a real person in a Telegram chat."
            )
        else:
            lang_instruction = (
                "IMPORTANT: Always reply in the SAME LANGUAGE as the user's message. "
                "If they write in Russian, reply in Russian. If in English, reply in English. "
                "Detect the language automatically and match it. "
                "Keep replies concise and natural — write like a real person in a Telegram chat, "
                "not like a formal letter."
            )
        parts = [lang_instruction]
        if profile.instructions:
            parts.append(f"Instructions:\n{profile.instructions}")
        if profile.personality:
            parts.append(f"Personality / tone:\n{profile.personality}")
        if profile.knowledge:
            parts.append(f"Knowledge base:\n{profile.knowledge}")
        if examples:
            ex_lines = []
            for ex in examples[:15]:
                ex_lines.append(f"Client: {ex.user_text}\nYou: {ex.agent_text}")
            parts.append("Few-shot examples:\n" + "\n---\n".join(ex_lines))
        if len(parts) == 1:
            parts.append("You are a helpful business assistant. Reply concisely and politely.")
        return "\n\n".join(parts)

    async def generate(
        self,
        user_text: str,
        profile: AgentProfileOut,
        examples: list[AgentExampleOut],
        model: str | None = None,
        history: list[dict[str, str]] | None = None,
        temperature: float = 0.7,
        max_tokens: int = 1024,
        language_mode: str = "auto",
        context_messages: int = 10,
    ) -> tuple[str, str, int, int]:
        """Returns (reply_text, model_used, tokens_in, tokens_out)."""
        if not self.ready:
            raise ApiError(503, "llm_not_configured", "GROQ_API_KEY is not set")

        model = model or self.default_model
        system = self._build_system(profile, examples, language_mode=language_mode)
        messages: list[dict[str, str]] = [{"role": "system", "content": system}]
        if history:
            messages.extend(history[-context_messages:])
        messages.append({"role": "user", "content": user_text})

        client = await self._client()
        resp = await client.post(
            f"{self.base_url}/chat/completions",
            headers={"Authorization": f"Bearer {self.api_key}", "Content-Type": "application/json"},
            json={"model": model, "messages": messages, "max_tokens": max_tokens, "temperature": temperature},
        )
        if resp.status_code != 200:
            agent_log.error("Groq API error %s: %s", resp.status_code, resp.text[:500])
            raise ApiError(502, "llm_error", f"LLM API returned {resp.status_code}")

        data = resp.json()
        reply = data["choices"][0]["message"]["content"].strip()
        usage = data.get("usage", {})
        return reply, model, usage.get("prompt_tokens", 0), usage.get("completion_tokens", 0)

    async def close(self) -> None:
        if self._http and not self._http.is_closed:
            await self._http.aclose()


