async def parse_gifts_for_owner(
    db: aiosqlite.Connection,
    owner_id: int,
    client: TelegramClient,
) -> int:
    """Fetches available gifts via the Telegram API and stores them. Returns count."""
    try:
        result = await client(functions.payments.GetStarGiftsRequest(hash=0))
    except Exception as e:
        gift_log.warning("GetStarGiftsRequest failed for owner=%s: %s", owner_id, type(e).__name__)
        return 0

    gifts = getattr(result, "gifts", []) or []
    count = 0
    ts = now()
    for g in gifts:
        gift_id = str(getattr(g, "id", "")) or str(count)
        title = getattr(g, "title", "") or ""
        stars = getattr(g, "stars", None)
        if isinstance(stars, int) and stars < 0:
            stars = None
        limited = bool(getattr(g, "limited", False))
        total = getattr(g, "availability_total", None)
        remaining = getattr(g, "availability_remains", None)

        sticker = getattr(g, "sticker", None)
        emoji_attr = getattr(g, "alt", None) or getattr(sticker, "alt", None) or ""

        await db.execute(
            """INSERT INTO gift_market
               (owner_id, gift_id, title, price_stars, price_ton, emoji, limited,
                total_count, remaining_count, image_url, source_url, parsed_at)
               VALUES (?, ?, ?, ?, NULL, ?, ?, ?, ?, NULL, NULL, ?)
               ON CONFLICT(owner_id, gift_id) DO UPDATE SET
                   title=excluded.title, price_stars=excluded.price_stars, emoji=excluded.emoji,
                   limited=excluded.limited, total_count=excluded.total_count,
                   remaining_count=excluded.remaining_count, parsed_at=excluded.parsed_at""",
            (owner_id, gift_id, title, stars, emoji_attr, int(limited), total, remaining, ts),
        )
        count += 1

    await db.commit()
    gift_log.info("parsed %d gifts for owner=%s", count, owner_id)
    return count


