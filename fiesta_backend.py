@gifts_router.post("/parse", response_model=dict)
async def trigger_gift_parse(
    user: TgUser = Depends(current_user),
    manager: LoginManager = Depends(logins),
) -> dict[str, Any]:
    rate_limit(f"gift-parse:{user.id}", 3, 300)
    async with connect() as db:
        rows = await db.execute_fetchall(
            "SELECT * FROM sessions WHERE owner_id = ? AND is_active = 1 LIMIT 1",
            (user.id,),
        )
        if not rows:
            raise ApiError(400, "no_sessions", "Connect at least one Telegram session first")
        row = rows[0]
        path = _file_for(row)

    if not settings.telethon_ready:
        raise ApiError(503, "api_not_configured", "Telethon API credentials not set")

    client = TelegramClient(
        str(path), settings.api_id, settings.api_hash,
        device_model="FiestaAI Gifts", timeout=20,
    )
    try:
        await asyncio.wait_for(client.connect(), 20)
        if not await client.is_user_authorized():
            raise ApiError(400, "session_unauthorized", "Session is not authorized")
        async with connect() as db:
            count = await parse_gifts_for_owner(db, user.id, client)
    finally:
        with contextlib.suppress(Exception):
            await asyncio.wait_for(client.disconnect(), 10)

    return {"ok": True, "parsed": count}


