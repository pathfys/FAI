@sessions_router.patch("/{session_id}", response_model=SessionOut)
async def patch_session(
    body: SessionPatch, session_id: str = SessionId, user: TgUser = Depends(current_user)
) -> SessionOut:
    changes: dict[str, Any] = body.model_dump(exclude_none=True)
    async with connect() as db:
        await _owned(db, user.id, session_id)
        if changes:
            if "is_active" in changes:
                changes["is_active"] = int(changes["is_active"])
            assignments = ", ".join(f"{k} = ?" for k in changes)  # keys come from SessionPatch only
            await db.execute(
                f"UPDATE sessions SET {assignments} WHERE id = ? AND owner_id = ?",
                (*changes.values(), session_id, user.id),
            )
            await db.commit()
        return _out(await _owned(db, user.id, session_id))


@sessions_router.delete("/{session_id}", response_model=DeleteOut)
async def delete_session(
    session_id: str = SessionId, user: TgUser = Depends(current_user), manager: LoginManager = Depends(logins)
) -> DeleteOut:
    async with connect() as db:
        row = await _owned(db, user.id, session_id)
        logged_out = await manager.logout_file(_file_for(row))
        await db.execute("DELETE FROM sessions WHERE id = ? AND owner_id = ?", (session_id, user.id))
        await db.commit()
    sessions_log.info("session deleted id=%s owner=%s logged_out=%s", session_id, user.id, logged_out)
    return DeleteOut(ok=True, logged_out=logged_out)


@sessions_router.post("/{session_id}/check", response_model=SessionCheckOut)
async def check_session(
    session_id: str = SessionId, user: TgUser = Depends(current_user), manager: LoginManager = Depends(logins)
) -> SessionCheckOut:
    rate_limit(f"check:{user.id}", 10, 60)
    async with connect() as db:
        row = await _owned(db, user.id, session_id)
        try:
            ok, reason, acc = await manager.check_file(_file_for(row))
        except LoginError as e:
            _raise(e)
        if ok and acc:
            await db.execute(
                """UPDATE sessions SET last_used_at = ?, first_name = ?, last_name = ?, username = ?
                   WHERE id = ? AND owner_id = ?""",
                (now(), acc.first_name, acc.last_name, acc.username, session_id, user.id),
            )
        elif ok is False:
            await db.execute("UPDATE sessions SET is_active = 0 WHERE id = ? AND owner_id = ?", (session_id, user.id))
        await db.commit()
        row = await _owned(db, user.id, session_id)
    return SessionCheckOut(ok=bool(ok), session=_out(row), reason=reason)


