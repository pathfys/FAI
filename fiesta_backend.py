# app/services/dispatcher_bridge.py
#   Read-only bridge to the AI dispatcher's tables in the shared SQLite file.
#
#   The dispatcher (business_dispatcher) owns `messages`, `chat_state` and
#   `business_connections`; this module never writes to them. Their exact columns
#   are not fixed by the spec, so they are detected at runtime:
#
#     messages.chat      chat_id | peer_id | client_id | user_chat_id
#     messages.text      text | content | message | body | message_text
#     messages.ts        created_at | ts | timestamp | date | sent_at | time | created
#                        (unix seconds / milliseconds, or ISO text treated as UTC)
#     messages.role      role | direction | sender | sender_type | author | from_role | kind | type | source
#                        values like user/client/in → incoming, assistant/bot/out → bot,
#                        owner/manual/operator → manual, draft/diagnostic → draft, error/failed → error
#     or flags           from_me | is_outgoing | outgoing | is_bot  (+ is_manual, is_draft)
#     messages.status    status | state            (error/failed → error, draft/diagnostic → draft)
#     messages.error     error | error_text | last_error
#     owner scoping      messages.business_connection_id → business_connections.(id|business_connection_id|connection_id)
#                        whose user_id | owner_id | user_chat_id equals the Mini App owner;
#                        or messages.owner_id directly. Without either, every allowed owner
#                        sees all rows (the panel is single-tenant by ALLOWED_USER_IDS).
# ════════════════════════════════════════════════════════════════════════════

