def _str(v: Any, limit: int = 256) -> str | None:
    return v[:limit] if isinstance(v, str) and v else None


async def current_user(x_init_data: str | None = Header(default=None, alias="X-Init-Data")) -> TgUser:
    """FastAPI dependency: validates X-Init-Data and the owner allow-list."""
    try:
        data = validate_init_data(x_init_data or "", settings.bot_token, settings.init_data_max_age)
    except InitDataError as e:
        raise ApiError(401, e.code, "Open the Mini App from Telegram") from None

    user = data["user"]
    uid = int(user["id"])
    if uid not in settings.allowed_user_ids:
        raise ApiError(403, "not_allowed", "This Telegram account is not allowed", user_id=uid)

    photo = _str(user.get("photo_url"), 1024)
    if photo and not photo.startswith("https://"):
        photo = None
    return TgUser(
        id=uid,
        first_name=_str(user.get("first_name")) or "",
        last_name=_str(user.get("last_name")),
        username=_str(user.get("username"), 64),
        photo_url=photo,
        language_code=_str(user.get("language_code"), 16),
    )


# ════════════════════════════════════════════════════════════════════════════
# app/ratelimit.py
#   In-memory sliding-window rate limiter (single uvicorn worker is assumed).
# ════════════════════════════════════════════════════════════════════════════

_buckets: dict[str, deque[float]] = defaultdict(deque)


def rate_limit(key: str, limit: int, window: float) -> None:
    """Raises 429 when `key` was hit more than `limit` times in `window` seconds."""
    now = time.monotonic()
    q = _buckets[key]
    while q and now - q[0] >= window:
        q.popleft()
    if len(q) >= limit:
        retry_after = int(window - (now - q[0])) + 1
        raise ApiError(429, "rate_limited", "Too many requests", retry_after=retry_after)
    q.append(now)


def reset_rate_limits() -> None:
    _buckets.clear()


