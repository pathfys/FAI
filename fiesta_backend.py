def logins(request: Request) -> LoginManager:
    return request.app.state.logins


def _raise(e: LoginError) -> None:
    raise ApiError(e.status, e.code, e.message, **e.extra) from None


def _out(row: aiosqlite.Row) -> SessionOut:
    return SessionOut(
        id=row["id"],
        tg_user_id=row["tg_user_id"],
        phone_masked=mask_phone(row["phone"]),
        first_name=row["first_name"],
        last_name=row["last_name"],
        username=row["username"],
        usage_type=row["usage_type"] if row["usage_type"] in ("monitor", "dispatcher") else "monitor",
        is_active=bool(row["is_active"]),
        connected_at=row["connected_at"],
        last_used_at=row["last_used_at"],
    )


def _file_for(row: Any) -> Path:
    """Session file of a row, refusing anything outside SESSIONS_DIR."""
    base = settings.sessions_dir.resolve()
    stored = (row["session_file"] or "").strip()
    if stored:
        p = Path(stored).resolve()
        if p.parent == base and p.suffix == ".session":
            return p
    return base / f"{row['id']}.session"


async def _owned(db: aiosqlite.Connection, owner_id: int, session_id: str) -> aiosqlite.Row:
    row = await (
        await db.execute("SELECT * FROM sessions WHERE id = ? AND owner_id = ?", (session_id, owner_id))
    ).fetchone()
    if not row:
        raise ApiError(404, "not_found", "Session not found")
    return row


