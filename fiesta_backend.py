async def today_counts(db: aiosqlite.Connection, owner_id: int, tz_name: str) -> dict[str, Any]:
    out = {k: 0 for k in KINDS}
    out["last_activity_at"] = None
    out["available"] = False
    s = await detect(db)
    if not s:
        return out
    out["available"] = True
    scope, params = _scope(s, owner_id)

    if s.ts:
        last = await db.execute_fetchall(
            f"SELECT m.{q(s.ts)} FROM messages m WHERE {scope} ORDER BY m.rowid DESC LIMIT 1", params
        )
        out["last_activity_at"] = to_unix(last[0][0]) if last else None

    since = await _since_condition(db, s, start_of_today(tz_name))
    if since is None:
        return out
    cond, cparams = since

    def col(attr: str) -> str:
        name = getattr(s, attr)
        return f"m.{q(name)}" if name else "NULL"

    err = (
        f"CASE WHEN {col('error')} IS NULL OR {col('error')} IN ('', 0, '0') THEN NULL ELSE 1 END"
        if s.error
        else "NULL"
    )
    rows = await db.execute_fetchall(
        f"""SELECT {col('role')} AS role, {col('status')} AS status, {col('outgoing')} AS outgoing,
                   {col('manual')} AS manual, {col('draft')} AS draft, {err} AS error, COUNT(*) AS n
            FROM messages m WHERE {scope} AND {cond}
            GROUP BY 1, 2, 3, 4, 5, 6""",
        params + cparams,
    )
    for r in rows:
        kind = classify(dict(r), s)
        if kind:
            out[kind] += int(r["n"])
    return out


def _event(row: aiosqlite.Row, kind: str) -> dict[str, Any]:
    chat = int(row["chat"])
    text = str(row["text"] or "")[:MAX_TEXT]
    error = str(row["error"])[:500] if _has_error(row["error"]) else None
    return {
        "id": str(row["_rid"]),
        "chat_id": chat,
        "chat_label": mask_chat(chat),
        "kind": kind,
        "text": text,
        "prompt": None,
        "error": error,
        "ts": to_unix(row["ts"]),
    }


async def _prompt_for(db: aiosqlite.Connection, s: Schema, row: aiosqlite.Row) -> str | None:
    """The client message a reply answered: the previous incoming row in that chat."""
    where = [f"m.{q(s.chat)} = ?", "m.rowid < ?"]
    params: list[Any] = [row["chat"], row["_rid"]]
    if s.conn and row["conn"] is not None:
        where.append(f"m.{q(s.conn)} = ?")
        params.append(row["conn"])
    prev = await db.execute_fetchall(
        f"SELECT {_select_list(s)} FROM messages m WHERE {' AND '.join(where)} ORDER BY m.rowid DESC LIMIT 8",
        params,
    )
    # Skip consecutive replies (multi-part answers) until the client's message.
    for p in prev:
        if classify(dict(p), s) == "incoming":
            return str(p["text"] or "")[:MAX_TEXT] or None
    return None


async def list_events(
    db: aiosqlite.Connection,
    owner_id: int,
    log_filter: str,
    cursor: int | None,
    limit: int,
    max_scan: int = 2000,
) -> tuple[list[dict[str, Any]], str | None, bool]:
    """(events, next_cursor, available). Paged by rowid, newest first."""
    s = await detect(db)
    if not s:
        return [], None, False
    wanted = FILTERS.get(log_filter, FILTERS["all"])
    scope, params = _scope(s, owner_id)

    items: list[dict[str, Any]] = []
    scanned = 0
    upper = cursor
    batch = max(limit * 3, 60)
    while len(items) < limit and scanned < max_scan:
        where = [scope]
        p = list(params)
        if upper is not None:
            where.append("m.rowid < ?")
            p.append(upper)
        rows = await db.execute_fetchall(
            f"SELECT {_select_list(s)} FROM messages m WHERE {' AND '.join(where)} ORDER BY m.rowid DESC LIMIT ?",
            p + [batch],
        )
        if not rows:
            return items, None, True
        for r in rows:
            scanned += 1
            upper = int(r["_rid"])
            if r["chat"] is None:
                continue
            kind = classify(dict(r), s)
            if kind not in wanted:
                continue
            ev = _event(r, kind)
            if kind in ("bot", "manual", "draft"):
                ev["prompt"] = await _prompt_for(db, s, r)
            items.append(ev)
            if len(items) >= limit:
                return items, str(upper), True
        if len(rows) < batch:
            return items, None, True
    return items, (str(upper) if upper is not None else None), True


async def read_dialog(
    db: aiosqlite.Connection, owner_id: int, chat_id: int, limit: int
) -> tuple[list[dict[str, Any]], bool]:
    """Last `limit` messages of a chat, oldest first."""
    s = await detect(db)
    if not s:
        return [], False
    scope, params = _scope(s, owner_id)
    rows = await db.execute_fetchall(
        f"""SELECT {_select_list(s)} FROM messages m
            WHERE {scope} AND m.{q(s.chat)} = ? ORDER BY m.rowid DESC LIMIT ?""",
        params + [chat_id, limit],
    )
    out = []
    for r in reversed(rows):
        kind = classify(dict(r), s)
        if not kind:
            continue
        ev = _event(r, kind)
        out.append({k: ev[k] for k in ("id", "kind", "text", "error", "ts")})
    return out, True


