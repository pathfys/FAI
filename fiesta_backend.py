async def update_user_settings(db: aiosqlite.Connection, owner_id: int, changes: dict[str, Any]) -> None:
    changes = {k: v for k, v in changes.items() if k in EDITABLE}
    if not changes:
        return
    assignments = ", ".join(f"{k} = ?" for k in changes)
    values = [int(v) if isinstance(v, bool) else v for v in changes.values()]
    await db.execute(
        f"UPDATE user_settings SET {assignments}, updated_at = ? WHERE owner_id = ?",
        (*values, now(), owner_id),
    )
    await db.commit()


async def store_chat_filter(db: aiosqlite.Connection, owner_id: int, kind: str, chat_id: int, label: str | None) -> None:
    other = "blacklist" if kind == "whitelist" else "whitelist"
    # A chat can't be both allowed and blocked.
    await db.execute(
        "DELETE FROM chat_filters WHERE owner_id = ? AND kind = ? AND chat_id = ?",
        (owner_id, other, chat_id),
    )
    await db.execute(
        """INSERT INTO chat_filters (owner_id, kind, chat_id, label, added_at) VALUES (?, ?, ?, ?, ?)
           ON CONFLICT(owner_id, kind, chat_id) DO UPDATE SET label = excluded.label""",
        (owner_id, kind, chat_id, label, now()),
    )
    await db.commit()


async def delete_chat_filter(db: aiosqlite.Connection, owner_id: int, kind: str, chat_id: int) -> bool:
    cur = await db.execute(
        "DELETE FROM chat_filters WHERE owner_id = ? AND kind = ? AND chat_id = ?",
        (owner_id, kind, chat_id),
    )
    await db.commit()
    return cur.rowcount > 0


