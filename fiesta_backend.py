dispatch_log = logging.getLogger("fiesta.dispatch")


class MessageDispatcher:
    """Manages background Telethon clients that listen + auto-reply."""

    def __init__(
        self,
        llm: LLMAgent,
        api_id: int | None,
        api_hash: str | None,
        sessions_dir: Path,
    ) -> None:
        self.llm = llm
        self.api_id = api_id
        self.api_hash = api_hash
        self.sessions_dir = sessions_dir
        self._clients: dict[str, TelegramClient] = {}
        self._tasks: dict[str, asyncio.Task[None]] = {}
        self._counters: dict[int, dict[str, int]] = defaultdict(lambda: {"in": 0, "out": 0, "err": 0})
        self._chat_locks: dict[int, asyncio.Lock] = {}
        self._msg_tasks: set[asyncio.Task[None]] = set()

    def _chat_lock(self, chat_id: int) -> asyncio.Lock:
        if chat_id not in self._chat_locks:
            self._chat_locks[chat_id] = asyncio.Lock()
        return self._chat_locks[chat_id]

    @property
    def active_count(self) -> int:
        return len(self._clients)

    def counters_for(self, owner_id: int) -> dict[str, int]:
        return self._counters[owner_id]

    async def _appeal_spam_block(
        self, client: TelegramClient, owner_id: int, session_id: str,
    ) -> str:
        """Send /start to @SpamBot to check and appeal a spam block.
        Returns the SpamBot's final reply text."""
        from telethon.tl.types import PeerUser
        import asyncio as _aio

        spambot = "@SpamBot"
        result_text = ""
        try:
            entity = await client.get_entity(spambot)

            await client.send_message(entity, "/start")
            await _aio.sleep(3)
            msgs = await client.get_messages(entity, limit=1)
            first_reply = msgs[0].text if msgs else ""
            result_text = first_reply

            async with connect() as db:
                await record_activity(
                    db, owner_id, session_id, 0,
                    "spambot", f"SpamBot ответ: {first_reply[:300]}",
                )

            has_restriction = any(kw in first_reply.lower() for kw in [
                "ограничен", "limited", "restrict", "spam",
                "не можете", "cannot", "blocked",
            ])

            if has_restriction:
                await _aio.sleep(2)
                await client.send_message(entity, "/start")
                await _aio.sleep(4)
                msgs2 = await client.get_messages(entity, limit=1)
                appeal_reply = msgs2[0].text if msgs2 else ""
                result_text = appeal_reply

                async with connect() as db:
                    await record_activity(
                        db, owner_id, session_id, 0,
                        "spambot_appeal",
                        f"SpamBot апелляция: {appeal_reply[:300]}",
                    )

                dispatch_log.warning(
                    "spam block detected session=%s, appeal sent, reply: %s",
                    session_id, appeal_reply[:200],
                )
            else:
                dispatch_log.info(
                    "spam check OK session=%s: %s", session_id, first_reply[:200],
                )
        except Exception as exc:
            result_text = f"SpamBot error: {exc}"
            async with connect() as db:
                await record_activity(
                    db, owner_id, session_id, 0,
                    "spambot_error", f"Ошибка SpamBot: {exc}"[:300],
                )
            dispatch_log.error("spambot appeal failed session=%s: %s", session_id, exc)

        return result_text

    async def start_session(self, session_id: str, owner_id: int) -> bool:
        if session_id in self._clients:
            return True
        if not (self.api_id and self.api_hash):
            return False

        path = self.sessions_dir / f"{session_id}.session"
        if not path.exists():
            return False

        client = TelegramClient(
            str(path), self.api_id, self.api_hash,
            device_model="FiestaAI Agent", system_version="Server",
            connection_retries=3, timeout=20,
        )
        try:
            await asyncio.wait_for(client.connect(), 20)
            if not await client.is_user_authorized():
                await client.disconnect()
                return False
        except Exception:
            with contextlib.suppress(Exception):
                await client.disconnect()
            return False

        self._clients[session_id] = client
        self._tasks[session_id] = asyncio.create_task(
            self._listen(session_id, owner_id, client)
        )
        dispatch_log.info("dispatcher started session=%s owner=%s", session_id, owner_id)
        return True

    async def stop_session(self, session_id: str) -> None:
        task = self._tasks.pop(session_id, None)
        if task:
            task.cancel()
            with contextlib.suppress(asyncio.CancelledError):
                await task
        client = self._clients.pop(session_id, None)
        if client:
            with contextlib.suppress(Exception):
                await asyncio.wait_for(client.disconnect(), 10)

    async def _handle_message(
        self, session_id: str, owner_id: int, event: Any, sender: Any,
    ) -> None:
        """Handle a single incoming message — runs as a separate task for parallelism."""
        chat_id = event.chat_id
        text = event.raw_text or ""

        async with self._chat_lock(chat_id):
            self._counters[owner_id]["in"] += 1

            peer_name = ""
            peer_username = None
            try:
                peer_name = getattr(sender, "first_name", "") or ""
                if getattr(sender, "last_name", None):
                    peer_name += f" {sender.last_name}"
                peer_username = getattr(sender, "username", None)
            except Exception:
                pass

            peer_label = peer_username or peer_name.strip() or str(chat_id)

            async with connect() as db:
                cfg = await load_agent_config(db, owner_id)

                if not cfg.agent_enabled:
                    await record_activity(db, owner_id, session_id, chat_id,
                                          "skipped", f"Агент выключен, сообщение от {peer_label} пропущено")
                    return

                if cfg.working_hours_enabled:
                    current_hour = int(time.strftime("%H"))
                    if cfg.working_hours_start <= cfg.working_hours_end:
                        in_hours = cfg.working_hours_start <= current_hour < cfg.working_hours_end
                    else:
                        in_hours = current_hour >= cfg.working_hours_start or current_hour < cfg.working_hours_end
                    if not in_hours:
                        await record_activity(db, owner_id, session_id, chat_id,
                                              "skipped", f"Нерабочее время ({current_hour}:00), {peer_label} пропущен")
                        return

                if cfg.max_replies_daily > 0:
                    today_start = now() - (now() % 86400)
                    sent_today_rows = await db.execute_fetchall(
                        "SELECT COUNT(*) AS c FROM agent_messages WHERE owner_id = ? AND direction = 'out' AND ts >= ? AND error IS NULL",
                        (owner_id, today_start),
                    )
                    sent_today = sent_today_rows[0]["c"]
                    if sent_today >= cfg.max_replies_daily:
                        await record_activity(db, owner_id, session_id, chat_id,
                                              "skipped", f"Дневной лимит ({cfg.max_replies_daily}) исчерпан, {peer_label}")
                        return

                if cfg.max_concurrent_chats > 0:
                    active_tasks = len(self._msg_tasks)
                    if active_tasks > cfg.max_concurrent_chats:
                        await record_activity(db, owner_id, session_id, chat_id,
                                              "skipped", f"Лимит параллельных чатов ({cfg.max_concurrent_chats}), {peer_label}")
                        return

                if cfg.stop_words:
                    stop_list = [w.strip().lower() for w in cfg.stop_words.split(",") if w.strip()]
                    text_lower = text.lower()
                    for sw in stop_list:
                        if sw in text_lower:
                            await record_activity(db, owner_id, session_id, chat_id,
                                                  "skipped", f"Стоп-слово '{sw}' в сообщении от {peer_label}")
                            return

                if cfg.target_filter_enabled:
                    skip_reason = None
                    is_premium = getattr(sender, "premium", False)
                    has_photo = getattr(sender, "photo", None) is not None
                    has_uname = bool(getattr(sender, "username", None))
                    bio_text = ""
                    try:
                        full_user = await event.client(functions.users.GetFullUserRequest(sender.id))
                        bio_text = getattr(full_user.full_user, "about", "") or ""
                    except Exception:
                        pass
                    if cfg.target_premium_only and not is_premium:
                        skip_reason = f"Нет Premium у {peer_label}"
                    elif cfg.target_has_photo and not has_photo:
                        skip_reason = f"Нет фото профиля у {peer_label}"
                    elif cfg.target_has_username and not has_uname:
                        skip_reason = f"Нет username у {peer_label}"
                    elif cfg.target_skip_empty_bio and not bio_text.strip():
                        skip_reason = f"Пустое био у {peer_label}"
                    elif cfg.target_min_account_age_days > 0:
                        try:
                            from datetime import datetime, timezone
                            created = getattr(sender, "date", None)
                            if created:
                                age_days = (datetime.now(timezone.utc) - created).days
                                if age_days < cfg.target_min_account_age_days:
                                    skip_reason = f"Аккаунт {peer_label} слишком новый ({age_days}д < {cfg.target_min_account_age_days}д)"
                        except Exception:
                            pass
                    if skip_reason:
                        await record_activity(db, owner_id, session_id, chat_id,
                                              "filtered", f"Фильтр: {skip_reason}")
                        return

                await record_agent_message(db, owner_id, session_id, chat_id, "in", text[:4000])
                await record_activity(db, owner_id, session_id, chat_id,
                                      "msg_received", f"От {peer_label}: {text[:200]}")

                if cfg.auto_deal_create:
                    await upsert_deal(db, owner_id, session_id, chat_id,
                                      peer_name=peer_name.strip(), peer_username=peer_username)
                    await record_activity(db, owner_id, session_id, chat_id,
                                          "deal_updated", f"Сделка с {peer_label} — стадия: диалог")

                profile = await load_agent_profile(db, owner_id)
                examples = await list_agent_examples(db, owner_id)

                user_settings_row = await (
                    await db.execute("SELECT groq_model FROM user_settings WHERE owner_id = ?", (owner_id,))
                ).fetchone()
                model = user_settings_row["groq_model"] if user_settings_row else "llama-3.3-70b-versatile"

                ctx_limit = cfg.context_messages
                recent = await db.execute_fetchall(
                    f"SELECT direction, text FROM agent_messages WHERE owner_id = ? AND chat_id = ? ORDER BY id DESC LIMIT {ctx_limit}",
                    (owner_id, chat_id),
                )
                history = []
                for r in reversed(list(recent)):
                    role = "assistant" if r["direction"] == "out" else "user"
                    history.append({"role": role, "content": r["text"]})

            delay_min = cfg.reply_delay_min
            delay_max = cfg.reply_delay_max
            delay = delay_min + secrets.randbelow(max(1, delay_max - delay_min + 1))
            async with connect() as db:
                await record_activity(db, owner_id, session_id, chat_id,
                                      "delay_wait", f"Ожидание {delay}с перед ответом {peer_label}")
            dispatch_log.info("waiting %ds before reply to chat=%s", delay, chat_id)
            await asyncio.sleep(delay)

            try:
                async with connect() as db:
                    await record_activity(db, owner_id, session_id, chat_id,
                                          "generating", f"Генерация ответа для {peer_label} (модель: {model})")

                reply, used_model, tok_in, tok_out = await self.llm.generate(
                    text, profile, examples, model=model, history=history,
                    temperature=cfg.temperature,
                    max_tokens=cfg.response_max_length,
                    language_mode=cfg.language_mode,
                    context_messages=cfg.context_messages,
                )

                if cfg.split_messages:
                    parts = _split_message(reply)
                    for i, part in enumerate(parts):
                        if i > 0:
                            split_delay = cfg.split_delay_min + secrets.randbelow(
                                max(1, cfg.split_delay_max - cfg.split_delay_min + 1)
                            )
                            await asyncio.sleep(split_delay)
                        await event.respond(part)
                else:
                    parts = [reply]
                    await event.respond(reply)

                self._counters[owner_id]["out"] += 1
                async with connect() as db:
                    await record_agent_message(
                        db, owner_id, session_id, chat_id, "out", reply[:4000],
                        model=used_model, tokens_in=tok_in, tokens_out=tok_out,
                    )
                    parts_info = f" ({len(parts)} сообщ.)" if len(parts) > 1 else ""
                    await record_activity(db, owner_id, session_id, chat_id,
                                          "reply_sent",
                                          f"Ответ для {peer_label}{parts_info}, "
                                          f"токены: {tok_in}+{tok_out}")
                dispatch_log.info(
                    "replied chat=%s session=%s parts=%d tokens=%d+%d",
                    chat_id, session_id, len(parts), tok_in, tok_out,
                )
            except (
                tg.ChatWriteForbiddenError,
                tg.UserBannedInChannelError,
                tg.PeerFloodError,
            ) as e:
                self._counters[owner_id]["err"] += 1
                err_text = f"{type(e).__name__}: {e}"[:500]
                async with connect() as db:
                    await record_agent_message(
                        db, owner_id, session_id, chat_id, "out", "", error=err_text,
                    )
                    await record_activity(db, owner_id, session_id, chat_id,
                                          "spam_block",
                                          f"Спамблок для {peer_label}: {err_text}")
                dispatch_log.warning("spam block detected chat=%s: %s", chat_id, e)
                try:
                    await self._appeal_spam_block(event.client, owner_id, session_id)
                except Exception:
                    pass
            except Exception as e:
                self._counters[owner_id]["err"] += 1
                err_text = f"{type(e).__name__}: {e}"[:500]
                async with connect() as db:
                    await record_agent_message(
                        db, owner_id, session_id, chat_id, "out", "", error=err_text,
                    )
                    await record_activity(db, owner_id, session_id, chat_id,
                                          "reply_error", f"Ошибка для {peer_label}: {err_text}")
                dispatch_log.error("reply failed chat=%s: %s", chat_id, e)

    async def _listen(self, session_id: str, owner_id: int, client: TelegramClient) -> None:
        from telethon import events  # noqa: E402

        @client.on(events.NewMessage(incoming=True))
        async def handler(event: Any) -> None:
            if not event.is_private:
                return
            sender = await event.get_sender()
            if not sender:
                return
            is_bot = getattr(sender, "bot", False)
            if is_bot:
                try:
                    async with connect() as db:
                        cfg = await load_agent_config(db, owner_id)
                    if cfg.ignore_bots:
                        return
                except Exception:
                    return
            if not (event.raw_text or "").strip():
                return
            task = asyncio.create_task(
                self._handle_message(session_id, owner_id, event, sender)
            )
            self._msg_tasks.add(task)
            task.add_done_callback(self._msg_tasks.discard)

        try:
            await client.run_until_disconnected()
        except asyncio.CancelledError:
            pass
        except Exception as e:
            dispatch_log.error("listener crashed session=%s: %s", session_id, e)

    async def shutdown(self) -> None:
        for sid in list(self._tasks):
            await self.stop_session(sid)


# ════════════════════════════════════════════════════════════════════════════
# app/services/telegram_client.py
#   Connecting Telegram accounts "by code" with Telethon (no chat automation here).
#
#   Flow
#   ----
#   1. send_code(phone)    → TelegramClient on an in-memory StringSession, send_code_request.
#                            The pending login lives only in RAM under a random temp id,
#                            bound to the owner who started it. Nothing touches the disk.
#   2. verify(code)        → sign_in(phone, code, phone_code_hash).
#                            SessionPasswordNeededError → stage "password".
#   3. verify(password)    → sign_in(password=...). The password is never stored or logged.
#   4. finalize(...)       → only now the auth key is written to sessions/<id>.session
#                            (Telethon SQLite format, chmod 600, atomic rename).
#
#   Abandoned logins are disconnected after LOGIN_TTL seconds by cleanup_expired().
# ════════════════════════════════════════════════════════════════════════════

telethon_log = logging.getLogger("fiesta.telethon")

