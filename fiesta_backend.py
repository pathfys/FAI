async def _janitor(manager: LoginManager) -> None:
    while True:
        await asyncio.sleep(60)
        with contextlib.suppress(Exception):
            dropped = await manager.cleanup_expired()
            if dropped:
                log.info("expired pending logins dropped: %s", dropped)


async def _gift_loop(interval: int) -> None:
    """Periodically re-parses gift market for all owners with active sessions."""
    while True:
        await asyncio.sleep(interval)
        with contextlib.suppress(Exception):
            async with connect() as db:
                owners = await db.execute_fetchall(
                    "SELECT DISTINCT owner_id FROM sessions WHERE is_active = 1"
                )
                for row in owners:
                    oid = row["owner_id"]
                    sess = await db.execute_fetchall(
                        "SELECT * FROM sessions WHERE owner_id = ? AND is_active = 1 LIMIT 1",
                        (oid,),
                    )
                    if not sess:
                        continue
                    path = _file_for(sess[0])
                    if not path.exists() or not settings.telethon_ready:
                        continue
                    client = TelegramClient(
                        str(path), settings.api_id, settings.api_hash,
                        device_model="FiestaAI Gifts", timeout=20,
                    )
                    try:
                        await asyncio.wait_for(client.connect(), 20)
                        if await client.is_user_authorized():
                            await parse_gifts_for_owner(db, oid, client)
                    except Exception as e:
                        gift_log.debug("gift loop skip owner=%s: %s", oid, e)
                    finally:
                        with contextlib.suppress(Exception):
                            await asyncio.wait_for(client.disconnect(), 10)


async def _auto_start_dispatchers(dispatcher: MessageDispatcher) -> None:
    """Start dispatchers for all active dispatcher-type sessions."""
    async with connect() as db:
        rows = await db.execute_fetchall(
            "SELECT id, owner_id FROM sessions WHERE is_active = 1 AND usage_type = 'dispatcher'"
        )
    for row in rows:
        with contextlib.suppress(Exception):
            await dispatcher.start_session(row["id"], row["owner_id"])


@asynccontextmanager
async def lifespan(app: FastAPI) -> AsyncIterator[None]:
    await init_db()
    manager = LoginManager(
        settings.api_id,
        settings.api_hash,
        settings.sessions_dir,
        ttl=settings.login_ttl,
        client_factory=getattr(app.state, "client_factory", None),
    )
    manager.ensure_dir()
    app.state.logins = manager

    llm = LLMAgent(
        api_key=settings.groq_api_key,
        base_url=settings.groq_base_url,
    )
    app.state.llm = llm

    dispatcher = MessageDispatcher(
        llm=llm,
        api_id=settings.api_id,
        api_hash=settings.api_hash,
        sessions_dir=settings.sessions_dir,
    )
    app.state.dispatcher = dispatcher

    janitor = asyncio.create_task(_janitor(manager))
    gift_task = asyncio.create_task(_gift_loop(settings.gift_parse_interval))

    if llm.ready and settings.telethon_ready:
        await _auto_start_dispatchers(dispatcher)

    log.info(
        "FiestaAI API ready — db=%s sessions=%s llm=%s dispatcher_sessions=%d",
        settings.db_path, settings.sessions_dir,
        "ready" if llm.ready else "not configured",
        dispatcher.active_count,
    )
    try:
        yield
    finally:
        janitor.cancel()
        gift_task.cancel()
        await dispatcher.shutdown()
        await llm.close()
        await manager.shutdown()


