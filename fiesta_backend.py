@sessions_router.post("/verify-code", response_model=VerifyOut)
async def verify_code(
    body: VerifyIn, user: TgUser = Depends(current_user), manager: LoginManager = Depends(logins)
) -> VerifyOut:
    rate_limit(f"verify:{user.id}", 30, 600)
    try:
        result = await manager.verify(user.id, body.session_temp_id, body.code, body.password)
    except LoginError as e:
        _raise(e)
    if not isinstance(result, CompletedLogin):
        return VerifyOut(status="password_required", password_hint=result.get("hint"))

    try:
        return VerifyOut(status="ok", session=await _persist(result, user.id, manager))
    except BaseException:
        # Never leave a signed-in authorization behind without a DB row.
        await manager.discard(result)
        raise


async def _persist(done: CompletedLogin, owner_id: int, manager: LoginManager) -> SessionOut:
    acc = done.account
    session_id = f"user_{acc.tg_user_id}_{phone_digits(acc.phone)}"
    async with connect() as db:
        existing = await (
            await db.execute("SELECT * FROM sessions WHERE id = ?", (session_id,))
        ).fetchone()
        if existing and existing["owner_id"] != owner_id:
            raise ApiError(409, "already_connected_other", "Account is connected by another owner")
        if existing:
            # Reconnecting the same account: end the previous authorization first,
            # it is about to be replaced by the new file.
            await manager.logout_file(_file_for(existing))

        path = await manager.finalize(done, session_id)
        ts = now()
        try:
            await _insert(db, done, owner_id, session_id, path, ts)
        except BaseException:
            path.unlink(missing_ok=True)
            raise
        row = await _owned(db, owner_id, session_id)
    sessions_log.info("session connected id=%s owner=%s usage=%s", session_id, owner_id, done.usage_type)
    return _out(row)


async def _insert(
    db: aiosqlite.Connection, done: CompletedLogin, owner_id: int, session_id: str, path: Path, ts: int
) -> None:
    acc = done.account
    await db.execute(
        """INSERT INTO sessions (id, owner_id, tg_user_id, phone, first_name, last_name, username,
                                 usage_type, is_active, connected_at, last_used_at, session_file)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, 1, ?, ?, ?)
           ON CONFLICT(id) DO UPDATE SET
               first_name = excluded.first_name, last_name = excluded.last_name,
               username = excluded.username, usage_type = excluded.usage_type, is_active = 1,
               connected_at = excluded.connected_at, last_used_at = excluded.last_used_at,
               session_file = excluded.session_file""",
        (
            session_id,
            owner_id,
            acc.tg_user_id,
            acc.phone,
            acc.first_name,
            acc.last_name,
            acc.username,
            done.usage_type,
            ts,
            None,  # last_used_at: set by the first successful check
            str(path),
        ),
    )
    await db.commit()


