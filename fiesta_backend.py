_schema_cache: dict[tuple[str, int], Schema | None] = {}


async def _columns(db: aiosqlite.Connection, table: str) -> list[str]:
    rows = await db.execute_fetchall(f"PRAGMA table_info({q(table)})")
    return [r[1] for r in rows]


def _pick(cols: Iterable[str], candidates: tuple[str, ...]) -> str | None:
    by_lower = {c.lower(): c for c in cols}
    for c in candidates:
        if c in by_lower:
            return by_lower[c]
    return None


async def detect(db: aiosqlite.Connection) -> Schema | None:
    version = (await db.execute_fetchall("PRAGMA schema_version"))[0][0]
    files = await db.execute_fetchall("SELECT file FROM pragma_database_list WHERE name = 'main'")
    key = (str(files[0][0]) if files else "", int(version))
    if key in _schema_cache:
        return _schema_cache[key]

    cols = await _columns(db, "messages")
    schema: Schema | None = None
    if cols:
        picked = {k: _pick(cols, v) for k, v in CAND.items()}
        if picked["chat"] and picked["text"]:
            conn_id = conn_owner = None
            if picked["conn"]:
                bc = await _columns(db, "business_connections")
                conn_id, conn_owner = _pick(bc, CONN_ID), _pick(bc, CONN_OWNER)
            schema = Schema(
                chat=picked["chat"],
                text=picked["text"],
                ts=picked["ts"],
                role=picked["role"],
                conn=picked["conn"],
                owner=picked["owner"],
                status=picked["status"],
                error=picked["error"],
                outgoing=picked["outgoing"],
                manual=picked["manual"],
                draft=picked["draft"],
                conn_id=conn_id,
                conn_owner=conn_owner,
            )
    _schema_cache[key] = schema
    return schema


# ─── classification ─────────────────────────────────────────────────────────


def _truthy(v: Any) -> bool:
    if isinstance(v, str):
        return v.strip().lower() in {"1", "true", "yes", "y", "t"}
    return bool(v)


def _has_error(v: Any) -> bool:
    return v not in (None, "", 0, "0")


def classify(values: dict[str, Any], s: Schema) -> str | None:
    """Kind of one row: incoming / bot / manual / draft / error, or None to skip."""
    status = str(values.get("status") or "").strip().lower()
    if (s.error and _has_error(values.get("error"))) or status in ERROR_STATUS:
        return "error"

    kind: str | None = None
    role = str(values.get("role") or "").strip().lower()
    if s.role and role:
        if role in SKIP_ROLES:
            return None
        kind = ROLE_KIND.get(role)
        if kind in ("error", "draft"):
            return kind
    if kind is None and s.outgoing:
        kind = "bot" if _truthy(values.get("outgoing")) else "incoming"
    if kind is None:
        kind = "incoming"

    if kind == "bot" and s.manual and _truthy(values.get("manual")):
        kind = "manual"
    if kind in ("bot", "manual") and ((s.draft and _truthy(values.get("draft"))) or status in DRAFT_STATUS):
        kind = "draft"
    return kind


def _select_list(s: Schema) -> str:
    def col(attr: str) -> str:
        name = getattr(s, attr)
        return f"m.{q(name)}" if name else "NULL"

    return ", ".join(
        [
            "m.rowid AS _rid",
            f"{col('chat')} AS chat",
            f"{col('text')} AS text",
            f"{col('ts')} AS ts",
            f"{col('role')} AS role",
            f"{col('conn')} AS conn",
            f"{col('status')} AS status",
            f"{col('error')} AS error",
            f"{col('outgoing')} AS outgoing",
            f"{col('manual')} AS manual",
            f"{col('draft')} AS draft",
        ]
    )


def _scope(s: Schema, owner_id: int) -> tuple[str, list[Any]]:
    if s.conn and s.conn_id and s.conn_owner:
        return (
            f"m.{q(s.conn)} IN (SELECT {q(s.conn_id)} FROM business_connections WHERE {q(s.conn_owner)} = ?)",
            [owner_id],
        )
    if s.owner:
        return f"m.{q(s.owner)} = ?", [owner_id]
    return "1 = 1", []


# ─── timestamps ─────────────────────────────────────────────────────────────


def to_unix(v: Any) -> int | None:
    if v is None or v == "":
        return None
    if isinstance(v, (int, float)) and not isinstance(v, bool):
        return int(v / 1000) if v > 1e12 else int(v)
    s = str(v).strip()
    if re.fullmatch(r"\d+(\.\d+)?", s):
        f = float(s)
        return int(f / 1000) if f > 1e12 else int(f)
    try:
        d = dt.datetime.fromisoformat(s.replace("Z", "+00:00"))
    except ValueError:
        return None
    if d.tzinfo is None:
        d = d.replace(tzinfo=dt.timezone.utc)  # SQLite CURRENT_TIMESTAMP is UTC
    return int(d.timestamp())


async def _since_condition(db: aiosqlite.Connection, s: Schema, since: int) -> tuple[str, list[Any]] | None:
    """SQL condition "ts >= since" in whatever format the column uses."""
    if not s.ts:
        return None
    rows = await db.execute_fetchall(
        f"SELECT {q(s.ts)}, typeof({q(s.ts)}) FROM messages WHERE {q(s.ts)} IS NOT NULL ORDER BY rowid DESC LIMIT 1"
    )
    if not rows:
        return None
    sample, kind = rows[0][0], rows[0][1]
    col = f"m.{q(s.ts)}"
    if kind in ("integer", "real"):
        return f"{col} >= ?", [since * 1000 if float(sample) > 1e12 else since]
    text = str(sample)
    if re.fullmatch(r"\d+(\.\d+)?", text.strip()):
        return f"CAST({col} AS REAL) >= ?", [since * 1000 if float(text) > 1e12 else since]
    sep = "T" if "T" in text else " "
    stamp = dt.datetime.fromtimestamp(since, dt.timezone.utc).strftime(f"%Y-%m-%d{sep}%H:%M:%S")
    return f"{col} >= ?", [stamp]


def start_of_today(tz_name: str) -> int:
    try:
        tz = ZoneInfo(tz_name)
    except Exception:  # noqa: BLE001
        tz = dt.timezone.utc
    now = dt.datetime.now(tz)
    return int(now.replace(hour=0, minute=0, second=0, microsecond=0).timestamp())


