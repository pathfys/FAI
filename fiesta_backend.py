class ApiError(Exception):
    def __init__(self, status: int, code: str, message: str = "", **extra: Any) -> None:
        super().__init__(message or code)
        self.status = status
        self.code = code
        self.message = message or code
        self.extra = extra


def _json(status: int, code: str, message: str, **extra: Any) -> JSONResponse:
    headers = {}
    if status == 429 and isinstance(extra.get("retry_after"), int):
        headers["Retry-After"] = str(extra["retry_after"])
    return JSONResponse({"error": code, "message": message, **extra}, status_code=status, headers=headers)


def install_error_handlers(app: FastAPI) -> None:
    @app.exception_handler(ApiError)
    async def _api_error(_: Request, exc: ApiError) -> JSONResponse:
        return _json(exc.status, exc.code, exc.message, **exc.extra)

    @app.exception_handler(RequestValidationError)
    async def _validation(_: Request, exc: RequestValidationError) -> JSONResponse:
        # Never echo the submitted values back ("input" may hold a phone code
        # or a 2FA password) — only where and what.
        fields = [
            {"loc": [str(p) for p in err.get("loc", ())][1:], "msg": err.get("msg", "")}
            for err in exc.errors()
        ]
        return _json(422, "validation", "Invalid request", fields=fields)

    @app.exception_handler(StarletteHTTPException)
    async def _http(_: Request, exc: StarletteHTTPException) -> JSONResponse:
        code = {404: "not_found", 405: "method_not_allowed"}.get(exc.status_code, "http_error")
        return _json(exc.status_code, code, str(exc.detail))


