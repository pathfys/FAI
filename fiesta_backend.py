def phone_digits(phone: str) -> str:
    return re.sub(r"\D", "", phone)


def mask_phone(phone: str) -> str:
    """+37368123456 → '+373 68 •••-•••' (country code guessed from common prefixes)."""
    d = phone_digits(phone)
    if not d:
        return ""
    cc_len = 1 if d[0] in "17" else 3 if d[:3] in _THREE_DIGIT_CC else 2
    cc, rest = d[:cc_len], d[cc_len:]
    return f"+{cc} {rest[:2]} •••-•••" if len(rest) > 4 else f"+{cc} •••"


_THREE_DIGIT_CC = {
    "373", "374", "375", "380", "370", "371", "372", "994", "995", "996", "998",
    "992", "993", "971", "972", "966", "962", "961", "212", "213", "216", "234",
    "254", "351", "352", "353", "354", "355", "356", "357", "358", "359", "385",
    "386", "387", "389", "420", "421", "852", "853", "855", "856", "880", "886",
}


def _code_via(sent: Any) -> tuple[str, int | None]:
    t = getattr(sent, "type", None)
    length = getattr(t, "length", None)
    if isinstance(t, types.auth.SentCodeTypeApp):
        via = "app"
    elif isinstance(t, (types.auth.SentCodeTypeSms,)):
        via = "sms"
    elif isinstance(t, (types.auth.SentCodeTypeCall, types.auth.SentCodeTypeFlashCall)):
        via = "call"
    else:
        name = type(t).__name__.lower()
        via = "sms" if "sms" in name else "call" if "call" in name else "other"
    return via, length if isinstance(length, int) and 3 <= length <= 8 else None


class LoginManager:
    def __init__(
        self,
        api_id: int | None,
        api_hash: str | None,
        sessions_dir: Path,
        ttl: int = 600,
        max_attempts: int = 5,
        max_pending_per_owner: int = 3,
        client_factory: ClientFactory | None = None,
    ) -> None:
        self.api_id = api_id
        self.api_hash = api_hash
        self.sessions_dir = sessions_dir
        self.ttl = ttl
        self.max_attempts = max_attempts
        self.max_pending_per_owner = max_pending_per_owner
        self._factory = client_factory or self._default_factory
        self._pending: dict[str, PendingLogin] = {}

    # ── plumbing ────────────────────────────────────────────────────────────

    def _default_factory(self, session: Any) -> TelegramClient:
        return TelegramClient(
            session,
            self.api_id,
            self.api_hash,
            device_model="FiestaAI",
            system_version="Server",
            app_version="FiestaAI 0.1",
            connection_retries=2,
            request_retries=2,
            timeout=15,
        )

    def _require_api(self) -> None:
        if not (self.api_id and self.api_hash):
            raise LoginError("api_not_configured", 503, "TELEGRAM_API_ID / TELEGRAM_API_HASH are not set")

    @property
    def pending_count(self) -> int:
        return len(self._pending)

    def ensure_dir(self) -> None:
        self.sessions_dir.mkdir(parents=True, exist_ok=True)
        with contextlib.suppress(OSError):
            os.chmod(self.sessions_dir, 0o700)

    @staticmethod
    async def _disconnect(client: TelegramClient) -> None:
        with contextlib.suppress(Exception):
            await asyncio.wait_for(client.disconnect(), 10)

    async def _drop(self, temp_id: str) -> None:
        p = self._pending.pop(temp_id, None)
        if p:
            await self._disconnect(p.client)

    def _get(self, owner_id: int, temp_id: str) -> PendingLogin:
        p = self._pending.get(temp_id)
        # Same answer for "unknown" and "someone else's": no probing of temp ids.
        if not p or p.owner_id != owner_id:
            raise LoginError("login_expired", 410, "Login not found or expired")
        return p

    # ── step 1 ──────────────────────────────────────────────────────────────

    async def send_code(self, owner_id: int, phone: str, usage_type: str) -> dict[str, Any]:
        self._require_api()
        for p in list(self._pending.values()):
            if p.owner_id == owner_id and p.phone == phone:
                await self._drop(p.temp_id)  # restarting the same number
        if sum(1 for p in self._pending.values() if p.owner_id == owner_id) >= self.max_pending_per_owner:
            raise LoginError("too_many_pending", 429, "Too many logins in progress", retry_after=60)

        client = self._factory(StringSession())
        try:
            await client.connect()
            sent = await client.send_code_request(phone)
        except tg.PhoneNumberInvalidError:
            await self._disconnect(client)
            raise LoginError("phone_invalid", 400, "Invalid phone number") from None
        except tg.PhoneNumberBannedError:
            await self._disconnect(client)
            raise LoginError("phone_banned", 400, "Phone number is banned") from None
        except tg.FloodWaitError as e:
            await self._disconnect(client)
            raise LoginError("flood_wait", 429, "Flood wait", retry_after=int(e.seconds)) from None
        except tg.PhoneNumberFloodError:
            await self._disconnect(client)
            raise LoginError("flood_wait", 429, "Too many codes requested", retry_after=3600) from None
        except tg.RPCError as e:
            await self._disconnect(client)
            raise LoginError("telegram_error", 502, type(e).__name__) from None
        except (OSError, ConnectionError, asyncio.TimeoutError):
            await self._disconnect(client)
            raise LoginError("telegram_unreachable", 502, "Cannot reach Telegram") from None

        temp_id = secrets.token_urlsafe(24)
        self._pending[temp_id] = PendingLogin(
            temp_id=temp_id,
            owner_id=owner_id,
            phone=phone,
            phone_code_hash=sent.phone_code_hash,
            usage_type=usage_type,
            client=client,
            created_at=time.monotonic(),
        )
        via, length = _code_via(sent)
        telethon_log.info("login started owner=%s phone=%s via=%s", owner_id, mask_phone(phone), via)
        return {
            "session_temp_id": temp_id,
            "phone_masked": mask_phone(phone),
            "code_via": via,
            "code_length": length,
            "expires_in": self.ttl,
        }

    # ── steps 2–3 ───────────────────────────────────────────────────────────

    async def verify(
        self,
        owner_id: int,
        temp_id: str,
        code: str | None = None,
        password: str | None = None,
    ) -> CompletedLogin | dict[str, Any]:
        """Returns CompletedLogin on success or {"status": "password_required", "hint": ...}."""
        p = self._get(owner_id, temp_id)
        if time.monotonic() - p.created_at > self.ttl:
            await self._drop(temp_id)
            raise LoginError("login_expired", 410, "Login expired")

        async with p.lock:
            if self._pending.get(temp_id) is not p:
                raise LoginError("login_expired", 410, "Login expired")
            try:
                if p.stage == "code":
                    if not code:
                        raise LoginError("validation", 422, "code is required")
                    try:
                        result = await p.client.sign_in(phone=p.phone, code=code, phone_code_hash=p.phone_code_hash)
                    except tg.SessionPasswordNeededError:
                        p.stage = "password"
                        p.attempts = 0
                        p.password_hint = await self._password_hint(p.client)
                        if not password:
                            return {"status": "password_required", "hint": p.password_hint}
                    else:
                        return await self._complete(p, result)

                if not password:
                    return {"status": "password_required", "hint": p.password_hint}
                result = await p.client.sign_in(password=password)
                return await self._complete(p, result)

            except LoginError:
                raise
            except tg.PhoneCodeInvalidError:
                await self._count_failure(p)
                raise LoginError("code_invalid", 400, "Wrong code", attempts_left=self.max_attempts - p.attempts) from None
            except tg.PasswordHashInvalidError:
                await self._count_failure(p)
                raise LoginError(
                    "password_invalid", 400, "Wrong password", attempts_left=self.max_attempts - p.attempts
                ) from None
            except (tg.PhoneCodeExpiredError, tg.PhoneCodeEmptyError):
                await self._drop(temp_id)
                raise LoginError("code_expired", 410, "Code expired") from None
            except tg.PhoneNumberUnoccupiedError:
                await self._drop(temp_id)
                raise LoginError("phone_unregistered", 400, "No account on this number") from None
            except (tg.FloodWaitError, tg.PhonePasswordFloodError) as e:
                seconds = int(getattr(e, "seconds", 0) or 600)
                raise LoginError("flood_wait", 429, "Flood wait", retry_after=seconds) from None
            except tg.RPCError as e:
                raise LoginError("telegram_error", 502, type(e).__name__) from None
            except (OSError, ConnectionError, asyncio.TimeoutError):
                raise LoginError("telegram_unreachable", 502, "Cannot reach Telegram") from None
            finally:
                password = None  # noqa: F841 — drop our reference to the 2FA password

    async def _count_failure(self, p: PendingLogin) -> None:
        p.attempts += 1
        if p.attempts >= self.max_attempts:
            await self._drop(p.temp_id)
            raise LoginError("too_many_attempts", 429, "Too many wrong attempts", retry_after=60)

    @staticmethod
    async def _password_hint(client: TelegramClient) -> str | None:
        with contextlib.suppress(Exception):
            pwd = await client(functions.account.GetPasswordRequest())
            hint = getattr(pwd, "hint", None)
            return hint[:64] if hint else None
        return None

    async def _complete(self, p: PendingLogin, result: Any) -> CompletedLogin:
        me = result if isinstance(result, types.User) else None
        if me is None:
            with contextlib.suppress(Exception):
                me = await p.client.get_me()
        if not isinstance(me, types.User):
            # sign_in returns auth.SentCode / TermsOfService for numbers without an account
            await self._drop(p.temp_id)
            raise LoginError("phone_unregistered", 400, "No account on this number")
        self._pending.pop(p.temp_id, None)  # the caller now owns the client
        return CompletedLogin(
            owner_id=p.owner_id,
            usage_type=p.usage_type,
            account=Account(
                tg_user_id=int(me.id),
                first_name=me.first_name,
                last_name=me.last_name,
                username=me.username,
                phone=p.phone,
            ),
            client=p.client,
        )

    # ── step 4 ──────────────────────────────────────────────────────────────

    def session_path(self, session_id: str) -> Path:
        if not re.fullmatch(r"[A-Za-z0-9_]{1,64}", session_id):
            raise ValueError("bad session id")
        return self.sessions_dir / f"{session_id}.session"

    async def finalize(self, done: CompletedLogin, session_id: str) -> Path:
        """Writes the auth key to sessions/<session_id>.session and disconnects."""
        self.ensure_dir()
        path = self.session_path(session_id)
        src = done.client.session
        tmp = self.sessions_dir / f".{session_id}.{secrets.token_hex(4)}.session"
        try:
            dst = SQLiteSession(str(tmp))
            dst.set_dc(src.dc_id, src.server_address, src.port)
            dst.auth_key = src.auth_key
            dst.save()
            dst.close()
            os.chmod(tmp, 0o600)
            os.replace(tmp, path)
        finally:
            with contextlib.suppress(FileNotFoundError):
                tmp.unlink()
            await self._disconnect(done.client)
        telethon_log.info("session saved id=%s owner=%s", session_id, done.owner_id)
        return path

    async def discard(self, done: CompletedLogin) -> None:
        """Logs the fresh authorization out (e.g. account already owned by someone else).
        The auth key is still in the in-memory session even after finalize() disconnected."""
        with contextlib.suppress(Exception):
            if not done.client.is_connected():
                await asyncio.wait_for(done.client.connect(), 15)
            await asyncio.wait_for(done.client.log_out(), 20)
        await self._disconnect(done.client)

    # ── other steps ─────────────────────────────────────────────────────────

    async def cancel(self, owner_id: int, temp_id: str) -> None:
        p = self._pending.get(temp_id)
        if p and p.owner_id == owner_id:
            await self._drop(temp_id)

    async def cleanup_expired(self) -> int:
        now = time.monotonic()
        stale = [k for k, p in self._pending.items() if now - p.created_at > self.ttl]
        for k in stale:
            await self._drop(k)
        return len(stale)

    async def shutdown(self) -> None:
        for k in list(self._pending):
            await self._drop(k)

    async def logout_file(self, path: Path) -> bool:
        """Terminates the Telegram authorization stored in `path`, then removes the file.
        Returns False when Telegram could not be reached / the key was already revoked
        (the file is removed anyway)."""
        logged_out = False
        if path.exists() and self.api_id and self.api_hash:
            client = self._factory(str(path))
            try:
                await asyncio.wait_for(client.connect(), 20)
                if await client.is_user_authorized():
                    logged_out = bool(await asyncio.wait_for(client.log_out(), 20))
            except Exception as e:  # noqa: BLE001 — best effort, the file goes anyway
                telethon_log.warning("logout failed for %s: %s", path.name, type(e).__name__)
            finally:
                await self._disconnect(client)
        with contextlib.suppress(FileNotFoundError):
            path.unlink()
        with contextlib.suppress(FileNotFoundError):
            Path(str(path) + "-journal").unlink()
        return logged_out

    async def check_file(self, path: Path) -> tuple[bool | None, str | None, Account | None]:
        """(ok, reason, account). ok=None means "could not tell" (network)."""
        self._require_api()
        if not path.exists():
            return False, "session_file_missing", None
        client = self._factory(str(path))
        try:
            await asyncio.wait_for(client.connect(), 20)
            if not await client.is_user_authorized():
                return False, "unauthorized", None
            me = await client.get_me()
            if not isinstance(me, types.User):
                return False, "unauthorized", None
            return True, None, Account(me.id, me.first_name, me.last_name, me.username, me.phone or "")
        except (tg.AuthKeyUnregisteredError, tg.SessionRevokedError, tg.SessionExpiredError):
            return False, "revoked", None
        except (tg.UserDeactivatedError, tg.UserDeactivatedBanError):
            return False, "deactivated", None
        except (OSError, ConnectionError, asyncio.TimeoutError):
            return None, "telegram_unreachable", None
        except tg.RPCError as e:
            return None, type(e).__name__, None
        finally:
            await self._disconnect(client)


